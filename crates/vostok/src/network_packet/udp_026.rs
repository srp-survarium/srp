//! UDP envelope used by retail 0.26g0 build 2777.
//!
//! Recovered from `try_parse_packet_header` at VA 0x3fa0a0 and
//! `fill_packet_header` at VA 0x3fb390. Acknowledgement continuations live at
//! the END of the datagram, in reverse order. This is separate from the later
//! protocol implemented by [`super::UdpPacket`]. Message framing is not part of
//! this envelope codec.

pub const MAX_DATAGRAM: usize = 512;
const NEWEST: u128 = 1 << 127;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Header {
    pub sequence: u8,
    pub ack_sequence: u8,
    /// Bit 127 acknowledges `ack_sequence`; bit 126 acknowledges its predecessor.
    /// The newest acknowledgement is implicit on the wire; bit 0 is unused.
    pub ack_mask: u128,
    /// Number of represented positions, including the implicit newest ack.
    /// Decoding yields 7, 14, ..., 126, or 127.
    pub ack_bits: u8,
    pub single_message: bool,
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum Error {
    #[error("truncated UDP header or acknowledgement continuation")]
    Truncated,
    #[error("UDP datagram exceeds the 512-byte limit")]
    TooLarge,
    #[error("acknowledgement history exceeds 127 positions")]
    AckOverflow,
    #[error("invalid acknowledgement history")]
    InvalidAck,
}

impl Header {
    /// Returns the header and a borrowed payload with the acknowledgement tail removed.
    pub fn decode(datagram: &[u8]) -> Result<(Self, &[u8]), Error> {
        if datagram.len() > MAX_DATAGRAM {
            return Err(Error::TooLarge);
        }
        if datagram.len() < 3 {
            return Err(Error::Truncated);
        }
        let mut end = datagram.len();
        let mut control = datagram[2];
        let mut bits = 1u32;
        let mut mask = NEWEST;
        while control & 0x80 != 0 {
            if bits > 120 {
                return Err(Error::AckOverflow);
            }
            mask |= u128::from(control & 0x7f) << (121 - bits);
            bits += 7;
            if end <= 3 {
                return Err(Error::Truncated);
            }
            end -= 1;
            control = datagram[end];
        }
        if bits <= 122 {
            mask |= u128::from(control >> 1) << (122 - bits);
        } else if control >> 1 != 0 {
            // The retail parser discards these out-of-range bits. Reject them
            // here so malformed encodings cannot masquerade as valid histories.
            return Err(Error::AckOverflow);
        }
        Ok((
            Self {
                sequence: datagram[0],
                ack_sequence: datagram[1],
                ack_mask: mask,
                ack_bits: (bits + 6).min(127) as u8,
                single_message: control & 1 == 0,
            },
            &datagram[3..end],
        ))
    }

    /// Encodes the selected acknowledgement horizon; older mask bits are omitted.
    pub fn encode(self, payload: &[u8]) -> Result<Vec<u8>, Error> {
        if !(1..=127).contains(&self.ack_bits) || self.ack_mask & NEWEST == 0 {
            return Err(Error::InvalidAck);
        }
        let extra = usize::from(self.ack_bits.saturating_sub(7)).div_ceil(7);
        if payload.len() > MAX_DATAGRAM - 3 - extra {
            return Err(Error::TooLarge);
        }
        let mut controls = Vec::with_capacity(extra + 1);
        for i in 0..extra {
            controls.push(0x80 | ((self.ack_mask >> (120 - 7 * i)) as u8 & 0x7f));
        }
        let last = if extra < 18 {
            ((self.ack_mask >> (121 - 7 * extra)) as u8 & 0x3f) << 1
        } else {
            0
        };
        controls.push(last | u8::from(!self.single_message));
        let mut result = Vec::with_capacity(3 + payload.len() + extra);
        result.extend([self.sequence, self.ack_sequence, controls[0]]);
        result.extend_from_slice(payload);
        result.extend(controls[1..].iter().rev());
        Ok(result)
    }

    pub fn acknowledges(self, sequence: u8) -> bool {
        let age = self.ack_sequence.wrapping_sub(sequence);
        age < self.ack_bits.min(127) && self.ack_mask & (NEWEST >> age) != 0
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn retail_machine_code_vectors() {
        // Generated by scripts/protocol-research/retail_header_oracle.py running
        // the hash-checked retail parser. No executable bytes are included.
        for line in include_str!("fixtures/026g-header.tsv").lines() {
            if line.starts_with('#') {
                continue;
            }
            let columns: Vec<_> = line.split('\t').collect();
            let hex = columns[0];
            let packet: Vec<u8> = (0..hex.len())
                .step_by(2)
                .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
                .collect();
            let (header, payload) = Header::decode(&packet).unwrap();
            assert_eq!(header.sequence, columns[1].parse::<u8>().unwrap());
            assert_eq!(header.ack_sequence, columns[2].parse::<u8>().unwrap());
            assert_eq!(header.ack_bits, columns[3].parse::<u8>().unwrap());
            assert_eq!(header.single_message, columns[4] == "1");
            assert_eq!(
                header.ack_mask,
                u128::from_str_radix(columns[5], 16).unwrap()
            );
            assert_eq!(payload, [0xfe]);
            assert_eq!(header.encode(payload).unwrap(), packet);
        }
    }

    #[test]
    fn rejects_truncation_overflow_and_oversized_datagrams() {
        for n in 0..3 {
            assert_eq!(Header::decode(&[0; 3][..n]), Err(Error::Truncated));
        }
        assert_eq!(Header::decode(&[0, 0, 0x80]), Err(Error::Truncated));
        assert_eq!(Header::decode(&[0, 0, 0x80, 0x80]), Err(Error::Truncated));
        assert_eq!(Header::decode(&[0x80; 22]), Err(Error::AckOverflow));
        assert_eq!(Header::decode(&[0; 513]), Err(Error::TooLarge));
    }

    #[test]
    fn acknowledgement_wraparound_and_horizon() {
        let header = Header {
            sequence: 10,
            ack_sequence: 1,
            ack_mask: NEWEST | (NEWEST >> 2),
            ack_bits: 7,
            single_message: true,
        };
        assert!(header.acknowledges(1));
        assert!(header.acknowledges(255));
        assert!(!header.acknowledges(0));
        assert!(!header.acknowledges(2));
        assert!(!header.acknowledges(249));
        assert!(header.encode(&[0; 509]).is_ok());
        assert_eq!(header.encode(&[0; 510]), Err(Error::TooLarge));
    }
}
